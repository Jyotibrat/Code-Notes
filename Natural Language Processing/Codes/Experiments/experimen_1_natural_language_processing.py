import re
import nltk
from nltk.corpus import stopwords
from nltk.stem import PorterStemmer

nltk.download('stopwords')

# Name: Bindupautra Jyotibrat
# Registration Number: 23BAI10963

# Initialize stemmer for reducing words to root form
stemmer = PorterStemmer()

# Load English stop-words
stop_words = set(stopwords.words('english'))

# Raw input text containing noise, mixed scripts, numbers, and symbols
text = "NLP is amazing!!! यह बहुत अच्छा है 2025 @AI"

# Name: Bindupautra Jyotibrat
# Registration Number: 23BAI10963

# Step 1: Tokenization
# Convert text to lowercase and split into words using regex
tokens = re.findall(r'\b\w+\b', text.lower())

print(tokens)

# Name: Bindupautra Jyotibrat
# Registration Number: 23BAI10963

# Step 2: Filtration
# Remove tokens containing digits or special characters
filtered_tokens = [word for word in tokens if word.isalpha()]

print(filtered_tokens)

# Name: Bindupautra Jyotibrat
# Registration Number: 23BAI10963

# Step 3: Script Validation
# Keep only English tokens by ensuring characters belong to English alphabet
english_tokens = [word for word in filtered_tokens if re.fullmatch(r'[a-z]+', word)]

print(english_tokens)

# Name: Bindupautra Jyotibrat
# Registration Number: 23BAI10963

# Step 4: Stop-word Removal
# Remove commonly used English words that do not add meaning
meaningful_tokens = [word for word in english_tokens if word not in stop_words]

print(meaningful_tokens)

# Name: Bindupautra Jyotibrat
# Registration Number: 23BAI10963

# Step 5: Stemming
# Reduce each word to its base/root form
normalized_tokens = [stemmer.stem(word) for word in meaningful_tokens]

# Display the final clean tokens
print("Normalized English Tokens:", normalized_tokens)