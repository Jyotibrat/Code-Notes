# Import necessary libraries
import nltk
import re
from nltk.util import ngrams
from nltk.tokenize import word_tokenize

# Download tokenizer data
nltk.download('punkt_tab')

# Name: Bindupautra Jyotibrat
# Registration No.: 23BAI10963

# Define the three corpora
corpus1 = "Write a python program to find all unigrams, bigrams and trigrams present in the given corpus."
corpus2 = "The students were studying happiness and replaying recorded lectures."
corpus3 = "NLP is amazing!!! यह बहुत अच्छा है 2025 @AI"

# Combine all corpora into one single corpus
combined_corpus = corpus1 + " " + corpus2 + " " + corpus3

print("Combined Corpus:\n")
print(combined_corpus)

# Name: Bindupautra Jyotibrat
# Registration No.: 23BAI10963

# Convert text to lowercase
combined_corpus = combined_corpus.lower()

# Remove special characters except Hindi characters and numbers
cleaned_text = re.sub(r"[^\w\s\u0900-\u097F]", "", combined_corpus)

print("Cleaned Text:\n")
print(cleaned_text)

# Name: Bindupautra Jyotibrat
# Registration No.: 23BAI10963

# Tokenize the cleaned text into words
tokens = word_tokenize(cleaned_text)

print("Tokens:\n")
print(tokens)

# Name: Bindupautra Jyotibrat
# Registration No.: 23BAI10963

# Generate Unigrams (single words)
unigrams = list(ngrams(tokens, 1))

print("Unigrams:\n")
print(unigrams)

# Name: Bindupautra Jyotibrat
# Registration No.: 23BAI10963

# Generate Bigrams (pairs of consecutive words)
bigrams = list(ngrams(tokens, 2))

print("Bigrams:\n")
print(bigrams)

# Name: Bindupautra Jyotibrat
# Registration No.: 23BAI10963

# Generate Trigrams (three consecutive words)
trigrams = list(ngrams(tokens, 3))

print("Trigrams:\n")
print(trigrams)