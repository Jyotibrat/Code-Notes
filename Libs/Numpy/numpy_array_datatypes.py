import numpy as np

"""
Data Types in Numpy:
1) integer - i
2) boolean - b
3) unsigned integer - u
4) float - f
5) complex float - c
6) timedelta - m
7) datetime - M
8) object - O
9) string - S
10) unicode string - U
11) fixed chunk of memory for other type (void) - V

unsigned integers are integers without sign which means the range of unsigned integer is 0 to 65535 if we are using 16 bits of int type and if we are using 32 bits of int type then the range is 0 to 4,294,967,295.
timedelta is a data which tells us the difference of time.
object is a datatype which is used for any kind of data which is unknow to numpy.
Unicode string is a sequence of characters where each character corresponds to a unique number, called a code point, defined by the Unicode standard.
"""

a = np.array([1,2,3,4])
a, a.dtype

# Here in a numpy if there is a single number which is of floating point then it converts all the rest of the numbers to floating point. Also in python we represent floating point numbers which has 0 after the point like this number. we do not write the 0 after the point.

b = np.array([1,2,3,4.0])
b, b.dtype

# Here we can see that the datatype shows that U6 where U means unicode but the 6 here means is that the longest word in the array (in our case it is banana which has a length of 6 that is why we are getting U6).

c = np.array(['apple', 'banana'])
c

"""
Here we convert the words from unicode string to normal string as it shows the dtype as '|S7'.
It shows 7 because the longest sequence of characters is 'bananas' which is 7.
"""

d = np.array(['apple', 'bananas'], dtype='S')
d

# This will throw an error because we are trying to convert a string to an integer.

e = np.array(['apple', 'bananas'], dtype='i')
e

# Here i4 means integer type of 4 byte which is of 32 bits that is why we get dtype as 'int32'.

f = np.array(['0', '1'], dtype='i4')
f

# Here i1 means integer type of 1 byte which is of 8 bits that is why we get dtype as 'int8'.

g = np.array(['0', '1'], dtype='i1')
g

# This will throw an error because integer can be of size 1 byte, 2 bytes, 4 bytes and 8 bytes.

h = np.array(['0', '1'], dtype='i3')
h

# This is how we define floating point datatype in numpy array.

i = np.array(['0.2', '1'], dtype='f')
i

# This is will throw an error as we cannot directly convert float to int in python.

j = np.array(['0.2', '1'], dtype='i')
j

# This is how we convert float to int in numpy array.

i.astype('i')

"""
We can do other conversions also like here we are converting to string type.
We get 32 at the end of S32 as the size of the float datatype is of 32 bits.
"""

i.astype('S')

# converting to boolean.

i.astype('bool')

# converting to unicode string.

i.astype('str')

# Sorting of an numpy array

l = np.array([1,5,3,7,2])
print(l)
l.sort() # Sorts in ascending order
print(l)
print(-np.sort(-l)) # There is no built in method for sorting in descending order in numpy so this is how we do sorting in descending order in a numpy array.