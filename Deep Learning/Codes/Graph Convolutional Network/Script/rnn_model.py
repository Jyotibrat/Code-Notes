def predict_for_year(target_year, df_full, df_proc, model, scaler_X, scaler_y, feature_cols, target_col):
    """
    Build a one-row feature vector for 'target_year' using the most recent known history,
    recompute rolling and lag features up to that year, then predict CO2 per capita.
    """
    if 'Years' not in df_proc.columns:
        raise ValueError("'Years' column is missing in processed data.")
    base = df_full.copy()
    base = base.sort_values('Years')

    for col in ['CO2_ma_3','CO2_ma_5','CO2_pct_change','CO2_lag_1','CO2_lag_2']:
        if col not in df_proc.columns:
            pass

    needed_cols = set(['Years', target_col]) | set([c for c in feature_cols if c in base.columns])
    base = base[[c for c in needed_cols if c in base.columns]].copy()

    last_known_year = int(base['Years'].max())
    if target_year <= last_known_year:
        df_ext = df_proc.copy()
    else:
        missing_years = [y for y in range(last_known_year + 1, target_year + 1)]
        new_rows = pd.DataFrame({'Years': missing_years})
        df_ext = pd.concat([base, new_rows], ignore_index=True)
        df_ext = df_ext.sort_values('Years')

        df_ext = advanced_feature_engineering(df_ext)

    if target_year not in df_ext['Years'].values:
        raise ValueError(f"Target year {target_year} not present after extension.")

    row = df_ext[df_ext['Years'] == target_year].copy()

    missing_feats = [c for c in feature_cols if c not in row.columns]
    if missing_feats:
        for c in missing_feats:
            row[c] = 0.0

    x_row = row[feature_cols].values.astype(float)

    x_row_clean = clean_data_for_scaling(x_row)
    x_row_scaled = scaler_X.transform(x_row_clean)

    y_pred_scaled = model.predict(x_row_scaled, verbose=0).flatten()
    y_pred = scaler_y.inverse_transform(y_pred_scaled.reshape(-1, 1)).flatten()[0]

    return float(y_pred)

