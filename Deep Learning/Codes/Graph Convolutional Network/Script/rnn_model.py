def clean_data_for_scaling(data):
    """Clean data by replacing inf/-inf values and extreme outliers"""
    data_cleaned = data.copy()

    # Replace infinity values with NaN
    data_cleaned = np.where(np.isinf(data_cleaned), np.nan, data_cleaned)

    # Replace extremely large values
    data_cleaned = np.where(np.abs(data_cleaned) > 1e10, np.nan, data_cleaned)

    # Fill NaN values with median
    if data_cleaned.ndim == 2:
        for i in range(data_cleaned.shape[1]):
            feature_data = data_cleaned[:, i]
            median_val = np.nanmedian(feature_data)
            if np.isnan(median_val):
                median_val = 0
            data_cleaned[:, i] = np.where(np.isnan(data_cleaned[:, i]), median_val, data_cleaned[:, i])
    else:
        median_val = np.nanmedian(data_cleaned)
        if np.isnan(median_val):
            median_val = 0
        data_cleaned = np.where(np.isnan(data_cleaned), median_val, data_cleaned)

    return data_cleaned

