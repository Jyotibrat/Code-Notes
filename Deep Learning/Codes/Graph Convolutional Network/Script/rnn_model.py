def advanced_feature_engineering(df):
    feature_columns = [
        'Access to electricity (% of population)',
        'CO2 emissions (metric tons per capita)',
        'Energy use (kg of oil equivalent per capita)',
    ]

    # Clean and filter data
    df_clean = df.dropna(subset=['CO2 emissions (metric tons per capita)'])

    # Use per capita CO2 as target (much smaller scale)
    target_col = 'CO2 emissions (metric tons per capita)'

    # Advanced outlier removal using IQR
    def remove_outliers_iqr(data, column, factor=1.5):
        if column in data.columns:
            Q1 = data[column].quantile(0.25)
            Q3 = data[column].quantile(0.75)
            IQR = Q3 - Q1
            lower = Q1 - factor * IQR
            upper = Q3 + factor * IQR
            return data[(data[column] >= lower) & (data[column] <= upper)]
        return data

    df_clean = remove_outliers_iqr(df_clean, target_col)

    if len(df_clean) > 0:
        # Rolling statistics for CO₂ per capita
        df_clean = df_clean.sort_values('Years') if 'Years' in df_clean.columns else df_clean
        df_clean['CO2_ma_3'] = df_clean[target_col].rolling(3, min_periods=1).mean()
        df_clean['CO2_ma_5'] = df_clean[target_col].rolling(5, min_periods=1).mean()

        # Rate of change
        df_clean['CO2_pct_change'] = df_clean[target_col].pct_change().fillna(0)

        # Lag features
        for lag in [1, 2]:
            df_clean[f'CO2_lag_{lag}'] = df_clean[target_col].shift(lag)

        # Fill NaN values
        df_clean = df_clean.interpolate(method='linear').fillna(method='bfill').fillna(method='ffill')

    return df_clean

