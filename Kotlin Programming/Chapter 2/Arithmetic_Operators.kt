// This is a program which demonstrates how Arithmetic Operations are performed in Kotlin

fun main(){
    // Addition Operation
    val a = 10
    val b = 4
    println(a+b) // Output: 14

    // Subtraction Operation
    println(a-b) // Output: 6

    // Multiplication Operation
    println(a*b) // Output: 40

    // Division Operation
    println(a/b) // Output: 2

    // Modulus Operation
    println(a%b) // Output: 2

    // Increment Operation
    var c = 5
    c++
    println(c) // Output: 6

    // Decrement Operation
    var d = 5
    // d--
    println(--d) // Output: 4

    // Addition Assignment Operation
    var e = 5
    e += 3
    println(e) // Output: 8

    // Subtraction Assignment Operation
    var f = 5
    f -= 3
    println(f) // Output: 2

    // Multiplication Assignment Operation
    var g = 5
    g *= 3
    println(g) // Output: 15

    // Division Assignment Operation
    var h = 5
    h /= 3
    println(h) // Output: 1

    // Modulus Assignment Operation
    var i = 5
    i %= 3
    println(i) // Output: 2    
}
