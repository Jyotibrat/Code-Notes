// This is a program that takes an integer input from the user and checks if it is even or odd.

fun main(){
    // This is how we take input from the user
    val ip = readln().toInt()
    println(ip%2==0);

    /*
    readln() is a function that reads a line of input from the user and returns it as a String.
    toInt() is a function that converts the String input to an Integer.
    */
}